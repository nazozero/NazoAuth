use nazo_auth::{OAuthClient, ValidatedClientRegistration};
use nazo_identity::TenantContext;
use uuid::Uuid;

pub(crate) fn client(tenant: TenantContext, public_id: &str) -> OAuthClient {
    OAuthClient {
        id: Uuid::new_v4(),
        tenant_id: tenant.tenant_id.as_uuid(),
        realm_id: tenant.realm_id.as_uuid(),
        organization_id: tenant.organization_id.as_uuid(),
        registration: ValidatedClientRegistration {
            client_id: public_id.into(),
            client_name: public_id.into(),
            client_type: "confidential".into(),
            redirect_uris: vec!["https://client.example/callback".into()],
            post_logout_redirect_uris: vec![],
            scopes: vec!["openid".into()],
            allowed_audiences: vec!["resource://default".into()],
            grant_types: vec!["authorization_code".into(), "refresh_token".into()],
            token_endpoint_auth_method: "client_secret_basic".into(),
            subject_type: "public".into(),
            sector_identifier_uri: None,
            sector_identifier_host: None,
            require_dpop_bound_tokens: false,
            allow_client_assertion_audience_array: false,
            allow_client_assertion_endpoint_audience: false,
            require_par_request_object: false,
            backchannel_token_delivery_mode: "poll".into(),
            backchannel_client_notification_endpoint: None,
            backchannel_authentication_request_signing_alg: None,
            backchannel_logout_uri: None,
            backchannel_logout_session_required: false,
            frontchannel_logout_uri: None,
            frontchannel_logout_session_required: false,
            tls_client_auth_subject_dn: None,
            tls_client_auth_cert_sha256: None,
            tls_client_auth_san_dns: vec![],
            tls_client_auth_san_uri: vec![],
            tls_client_auth_san_ip: vec![],
            tls_client_auth_san_email: vec![],
            jwks_uri: None,
            jwks: None,
            request_uris: vec![],
            initiate_login_uri: None,
            presentation: Default::default(),
            id_token_signed_response_alg: None,
            id_token_encrypted_response_alg: None,
            id_token_encrypted_response_enc: None,
            request_object_signing_alg: None,
            request_object_encryption_alg: None,
            request_object_encryption_enc: None,
            token_endpoint_auth_signing_alg: None,
            introspection_signed_response_alg: None,
            introspection_encrypted_response_alg: None,
            introspection_encrypted_response_enc: None,
            userinfo_signed_response_alg: None,
            userinfo_encrypted_response_alg: None,
            userinfo_encrypted_response_enc: None,
            authorization_signed_response_alg: None,
            authorization_encrypted_response_alg: None,
            authorization_encrypted_response_enc: None,
            security_policy: Default::default(),
        },
        require_mtls_bound_tokens: false,
        is_active: true,
    }
}
